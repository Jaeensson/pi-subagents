// Test fixture only: runs inside the disposable tmux pane, never calls a model.
import assert from "node:assert/strict";
import { EventEmitter } from "node:events";
import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
async function until(read, label, timeout = 20000) {
  const deadline = performance.now() + timeout;
  do {
    const value = await read();
    if (value) return value;
    await new Promise(resolve => setTimeout(resolve, 100));
  } while (performance.now() < deadline);
  throw new Error(`timed out: ${label}`);
}

export async function runSmokeDriver() {
  const { TMUX_SMOKE_ROOT: root, TMUX_SMOKE_SERVER: server, TMUX_SMOKE_SOCKET: socket,
    TMUX_SMOKE_PARENT: parentId, TMUX_SMOKE_BINARY: binary } = process.env;
  assert.match(server ?? "", /^pi-smoke-[a-f0-9]{32}$/);
  assert.ok(root && socket?.startsWith(root + path.sep), "private assigned socket required");
  // The pane environment is generated by our own disposable server.
  assert.equal(process.env.TMUX?.split(",")[0], socket, "own socket only");
  assert.equal(process.env.TMUX_PANE, parentId, "own assigned pane only");
  assert.equal(process.env.PI_CODING_AGENT_DIR, path.join(root, "agent"));
  // Detection must resolve tmux: no Herdr routing and no forced override.
  for (const key of Object.keys(process.env)) if (key.startsWith("HERDR_")) delete process.env[key];
  delete process.env.PI_SUBAGENT_MUX;
  // A realistic agent dir carries a readable settings.json; the extension never
  // creates one from scratch. Start tmux monitoring disabled so the first
  // activation is provably inert, then enable it through the real dialog.
  const settingsPath = path.join(root, "agent", "settings.json");
  try { await fs.writeFile(settingsPath, JSON.stringify({ subagent: { tmux: { enabled: false, viewers: true } } }) + "\n", { flag: "wx", mode: 0o600 }); }
  catch (error) { if (error.code !== "EEXIST") throw error; }
  // Agent-dir is set before any SDK or extension import (SDK caches its paths).
  const sdk = await import("@earendil-works/pi-coding-agent");
  assert.equal(sdk.getAgentDir(), path.join(root, "agent"));
  sdk.initTheme();
  const { default: extension } = await import("../index.ts");
  const { createMuxMonitor, nodeMonitorClock } = await import("../mux-monitor.ts");
  const { createViewerManager } = await import("../mux-viewers.ts");
  const { createTmuxAdapter } = await import("../tmux-adapter.ts");
  const { createSnapshotStore } = await import("../mux-files.ts");
  const { spawnTask } = await import("../process.ts");
  const runtime = await import("../runtime.ts");
  const { writeManifest } = await import("../store.ts");
  const checks = [], hooks = new Map(), cliObservations = new Map(), adapterLog = [];
  let command, adapterCalls = 0, monitoringTimers = 0, stores = 0;
  // Inspect and drive the real server through its own socket only.
  const cli = async args => {
    try {
      const stdout = String((await run(binary, ["-S", socket, ...args], { timeout: 5000, maxBuffer: 256 * 1024 })).stdout);
      const kind = args.slice(0, 2).join(" ");
      if (!cliObservations.has(kind)) cliObservations.set(kind, { args: args.slice(0, 3), stdout: stdout.slice(0, 240) });
      return stdout;
    } catch (error) { throw new Error(`tmux ${JSON.stringify(args)}: ${error.message}; ${error.stderr ?? ""}`); }
  };
  const clock = { ...nodeMonitorClock,
    setTimeout(fn, ms) { monitoringTimers++; return nodeMonitorClock.setTimeout(fn, ms); },
    setInterval(fn, ms) { monitoringTimers++; return nodeMonitorClock.setInterval(fn, ms); },
  };
  extension({
    on: (name, fn) => hooks.set(name, fn), registerTool() {}, registerMessageRenderer() {},
    registerCommand: (_name, value) => { command = value; }, sendMessage: () => {},
  }, { createMonitor: deps => createMuxMonitor({ ...deps, clock,
    adapterFactory: context => {
      adapterCalls++;
      return createTmuxAdapter(context, async (bin, args, options) => {
        try {
          const out = await run(bin, args, { timeout: options.timeout, maxBuffer: options.maxBuffer });
          if (adapterLog.length < 400) adapterLog.push({ args: args.slice(2, 8), out: String(out.stdout).slice(0, 160) });
          return String(out.stdout);
        } catch (error) {
          if (adapterLog.length < 400) adapterLog.push({ args: args.slice(2, 8), error: error.message, stderr: String(error.stderr ?? "").slice(0, 160) });
          throw error;
        }
      });
    },
    viewerFactory: host => createViewerManager(host, {
      storeFactory: () => {
        stores++;
        return createSnapshotStore({ tempRoot: root });
      },
    }),
  }) });
  const start = () => hooks.get("session_start")({ reason: "startup" }, { cwd: root, hasUI: false, sessionManager: { getSessionId: () => "smoke-parent" } });
  const toggle = async index => {
    let component;
    const theme = { fg: (_color, value) => value, bold: value => value, dim: value => value };
    const dialog = command.handler("", { mode: "tui", hasUI: true, scopedModels: [], modelRegistry: { getAvailable: () => [] },
      ui: { notify(message) { throw new Error(message); }, custom: factory => new Promise(resolve => { component = factory({ requestRender() {} }, theme, {}, resolve); }) } });
    assert.ok(component, "settings dialog opened");
    for (let i = 0; i < index; i++) component.handleInput("\x1b[B");
    component.handleInput(" "); component.handleInput("\x1b");
    await dialog;
  };
  const window = async () => {
    const out = await cli(["list-windows", "-a", "-F", "#{window_id} #{window_name}"]);
    return out.trim().split(/\r?\n/).map(line => line.trim()).filter(Boolean)
      .map(line => { const [id, ...name] = line.split(/\s+/); return { id, name: name.join(" ") }; })
      .find(entry => entry.name === "π subagents" || entry.name.startsWith("π subagents · "));
  };
  try {
    await start();
    assert.equal(adapterCalls, 0, "disabled tmux monitoring issues no adapter work");
    assert.equal(monitoringTimers, 0, "disabled tmux monitoring schedules no timers");
    assert.equal(stores, 0, "disabled tmux monitoring creates no snapshot stores");
    checks.push("outside-gate");
    const jobId = "smoke-batch";
    const job = { id: jobId, parentSessionId: "smoke-parent", mode: "parallel", status: "running", tasks: [],
      notifyOnComplete: true, notified: false, finished: false, chainRunnerDone: false, pendingSpawns: 0, persistenceReady: Promise.resolve(true) };
    runtime.jobs.set(jobId, job);
    await writeManifest(runtime.getJobsRoot(), "smoke-parent", { version: 1, jobId, parentSessionId: "smoke-parent",
      mode: "parallel", createdAt: Date.now(), updatedAt: Date.now(), notifyOnComplete: true, status: "running", tasks: [] });
    const child = async index => {
      const proc = new EventEmitter();
      proc.stdout = new EventEmitter(); proc.stderr = new EventEmitter(); proc.exitCode = null; proc.signalCode = null;
      proc.kill = signal => { queueMicrotask(() => { proc.exitCode = 143; proc.signalCode = signal; proc.emit("close", 143, signal); }); return true; };
      const task = await spawnTask({ name: "worker", source: "user", systemPrompt: "", tools: [], extensions: [] }, `Smoke task ${index}`, root, jobId,
        { taskId: `smoke-${index}`, name: `smoke-${index}`, modelCtx: { catalog: [] }, spawnProcess: () => proc });
      const emit = event => proc.stdout.emit("data", Buffer.from(JSON.stringify(event) + "\n"));
      emit({ type: "message_update", assistantMessageEvent: { type: "thinking_start", contentIndex: 0 } });
      emit({ type: "message_update", assistantMessageEvent: { type: "thinking_delta", delta: `thinking-${index}`, contentIndex: 0 } });
      emit({ type: "message_update", assistantMessageEvent: { type: "thinking_end", contentIndex: 0 } });
      emit({ type: "message_update", assistantMessageEvent: { type: "text_start", contentIndex: 1 } });
      emit({ type: "message_update", assistantMessageEvent: { type: "text_delta", delta: `text-${index}`, contentIndex: 1 } });
      emit({ type: "message_update", assistantMessageEvent: { type: "text_end", contentIndex: 1 } });
      emit({ type: "tool_execution_start", toolCallId: `tool-${index}`, toolName: "read", args: { path: `fixture-${index}` } });
      emit({ type: "tool_execution_end", toolCallId: `tool-${index}`, toolName: "read", result: { content: [{ type: "text", text: `tool-output-${index}` }] }, isError: false });
      return task;
    };
    for (let i = 1; i <= 4; i++) await child(i);
    // All four tasks must exist before the first layout pass: the viewer manager
    // builds the whole quad from one reconcile, so no peer is launched while an
    // anchor for a later slot is still being inspected.
    await until(() => {
      const running = [...runtime.tasks.values()].filter(task => task.jobId === jobId);
      return running.length === 4 && running.every(task => task.status === "running" && !task.setupPending && task.dispatchState === "running");
    }, "four dispatched fixture tasks");
    await toggle(6); // enable tmux monitoring through the registered /subagents dialog
    const owned = await until(window, "π subagents window");
    const panes = await until(async () => {
      const ids = (await cli(["list-panes", "-t", owned.id, "-F", "#{pane_id}"])).trim().split(/\s+/).filter(Boolean);
      return ids.length === 4 ? ids : undefined;
    }, "four viewer panes");
    checks.push("four-viewers");
    const borderStatus = (await cli(["show-options", "-w", "-t", owned.id, "-v", "pane-border-status"])).trim();
    const borderFormat = await cli(["show-options", "-w", "-t", owned.id, "-v", "pane-border-format"]);
    const automaticRename = (await cli(["show-options", "-w", "-t", owned.id, "-v", "automatic-rename"])).trim();
    assert.equal(borderStatus, "top");
    assert.match(borderFormat, /@pi_viewer_summary/);
    assert.equal(automaticRename, "off");
    checks.push("window-chrome");
    await until(async () => {
      for (const pane of panes) {
        const state = (await cli(["display-message", "-p", "-t", pane, "#{@pi_viewer_state}"])).trim();
        const summary = (await cli(["display-message", "-p", "-t", pane, "#{@pi_viewer_summary}"])).trim();
        if ((state !== "working" && state !== "idle") || !summary) return undefined;
      }
      return true;
    }, "viewer metadata");
    checks.push("viewer-metadata");
    await until(async () => (await cli(["display-message", "-p", "-t", parentId, "#{@pi_subagent_summary}"])).trim().startsWith("running 4"), "parent summary");
    checks.push("parent-summary");
    // Prove real viewer processes connected and rendered fixture content.
    await until(async () => {
      for (const pane of panes) {
        const text = await cli(["capture-pane", "-p", "-t", pane, "-S", "-80"]);
        if (/text-\d/.test(text)) return true;
      }
      return undefined;
    }, "viewer content", 30000);
    checks.push("viewer-content");
  } catch (error) {
    error.message += `; tmux observations=${JSON.stringify([...cliObservations.values()])}`;
    try { await fs.writeFile(path.join(root, "smoke-diagnostics.json"), JSON.stringify(adapterLog, null, 2)); } catch { /* best effort */ }
    throw error;
  }
  console.log(`TMUX_SMOKE_OK:${JSON.stringify(checks)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  runSmokeDriver().catch(error => { console.error(`TMUX_SMOKE_FAILED:${String(error.stack).replace(/[\r\n]+/g, " | ")}`); process.exitCode = 1; });
}
