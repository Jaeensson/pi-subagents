// Source-checkout-only, explicit opt-in validation. Importing this file is inert.
import { execFile } from "node:child_process";
import { randomUUID } from "node:crypto";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";

const FLOOR = { major: 3, minor: 2 };
const COMMAND_TIMEOUT_MS = 5000;
const MAX_BUFFER = 256 * 1024;
const TOTAL_DEADLINE_MS = 90000;
// The SDD/test runner itself lives in tmux, so the smoke always creates a
// uniquely named `-L` server and never resolves, reads, or mutates the ambient
// `$TMUX`/`-S` server.
const SERVER_NAME = /^pi-smoke-[a-f0-9]{32}$/;
const DRIVER_CHECKS = ["outside-gate", "four-viewers", "window-chrome", "viewer-metadata", "parent-summary"];

const quote = value => `'${value.replace(/'/g, `'\\''`)}'`;
const parseVersion = output => {
  const match = /^tmux\s+(?:next-)?(\d+)\.(\d+)/.exec(output.trim());
  return match ? { major: Number(match[1]), minor: Number(match[2]) } : undefined;
};
const atFloor = version => version.major > FLOOR.major || (version.major === FLOOR.major && version.minor >= FLOOR.minor);

async function until(read, timeout, label, deadline) {
  const limit = Math.min(performance.now() + timeout, deadline);
  do {
    const value = await read();
    if (value) return value;
    await new Promise(resolve => setTimeout(resolve, 100));
  } while (performance.now() < limit);
  throw new Error(`timed out: ${label}`);
}

/**
 * Runs the opt-in tmux monitoring smoke. Every tmux command is scoped to an
 * owned disposable `-L pi-smoke-<32hex>` server; the whole run is bounded and
 * the server is always killed, even on failure.
 * @param {Partial<{ binary: string; env: NodeJS.ProcessEnv; exec: (binary: string, args: string[], options: { env: NodeJS.ProcessEnv; timeout: number; maxBuffer: number }) => Promise<string>; tempRoot: string }>} supplied
 * @returns {Promise<string[]>} the check names that passed
 */
export async function runSmoke(supplied = {}) {
  const inherited = supplied.env ?? process.env;
  const binary = supplied.binary ?? inherited.PI_TMUX_BIN?.trim() ?? "tmux";
  const exec = supplied.exec ?? ((bin, args, options) => promisify(execFile)(bin, args, options).then(result => String(result.stdout)));
  const server = `pi-smoke-${randomUUID().replaceAll("-", "")}`;
  if (!SERVER_NAME.test(server)) throw new Error(`invalid disposable server name: ${server}`);
  const root = await fs.realpath(await fs.mkdtemp(path.join(supplied.tempRoot ?? os.tmpdir(), "ts-")));
  const tmuxDir = path.join(root, "tmux");
  await fs.mkdir(tmuxDir, { recursive: true, mode: 0o700 });
  // Strip ambient multiplexer identity and any Herdr/override routing so the
  // child server and driver can only ever see this run's own context.
  const env = Object.fromEntries(Object.entries(inherited).filter(([key]) =>
    !["TMUX", "TMUX_PANE", "TMUX_TMPDIR", "PI_SUBAGENT_MUX", "PI_TMUX_BIN"].includes(key) && !key.startsWith("HERDR_")));
  Object.assign(env, {
    HOME: path.join(root, "home"),
    XDG_CONFIG_HOME: path.join(root, ".config"),
    XDG_CACHE_HOME: path.join(root, ".cache"),
    XDG_DATA_HOME: path.join(root, ".local/share"),
    PI_CODING_AGENT_DIR: path.join(root, "agent"),
    PI_TMUX_BIN: binary,
    SHELL: "/bin/sh",
    TMPDIR: root, TEMP: root, TMP: root,
    TMUX_TMPDIR: tmuxDir,
  });
  const deadline = performance.now() + TOTAL_DEADLINE_MS;
  const invoke = async args => {
    try { return await exec(binary, ["-L", server, ...args], { env, timeout: COMMAND_TIMEOUT_MS, maxBuffer: MAX_BUFFER }); }
    catch (error) { throw new Error(`tmux ${JSON.stringify(args)}: ${error.message}\n${error.stderr ?? ""}`); }
  };
  let parent, socket, latest = "", started = false, failure, checks;
  try {
    await fs.chmod(root, 0o700);
    await fs.mkdir(env.PI_CODING_AGENT_DIR, { recursive: true, mode: 0o700 });
    // Refuse before creating anything when tmux is missing or below the floor.
    let version;
    try { version = parseVersion(await invoke(["-V"])); }
    catch (error) { throw new Error(`tmux is not installed or unusable: ${error.message}`); }
    if (!version) throw new Error("tmux did not report a parseable version");
    if (!atFloor(version)) throw new Error(`tmux ${version.major}.${version.minor} is below the 3.2 floor`);
    // The session is created with a placeholder command; the driver replaces it
    // via respawn-pane so the pane environment is generated by this server.
    const created = (await invoke(["new-session", "-d", "-s", "smoke", "-x", "240", "-y", "60", "-P", "-F",
      "#{pane_id} #{session_id} #{window_id}", "sleep 300"])).trim().split(/\s+/);
    started = true;
    parent = created[0];
    if (!/^%\d+$/.test(parent ?? "") || !/^@\d+$/.test(created[2] ?? "")) throw new Error(`invalid parent pane: ${created.join(" ")}`);
    // Keep the driver pane readable after it exits, and stay scoped to this window.
    await invoke(["set-option", "-w", "-t", created[2], "remain-on-exit", "on"]);
    socket = (await invoke(["display-message", "-p", "-t", parent, "#{socket_path}"])).trim();
    if (!socket || !socket.startsWith(root + path.sep)) throw new Error(`unowned tmux socket: ${socket}`);
    const driver = fileURLToPath(new URL("./tmux-monitor-smoke-driver.mjs", import.meta.url));
    const gate = {
      TMUX_SMOKE_ROOT: root, TMUX_SMOKE_SERVER: server, TMUX_SMOKE_SOCKET: socket,
      TMUX_SMOKE_PARENT: parent, TMUX_SMOKE_BINARY: binary,
      PI_TMUX_BIN: binary, PI_CODING_AGENT_DIR: env.PI_CODING_AGENT_DIR,
    };
    const command = ["/usr/bin/env", ...Object.entries(gate).map(([key, value]) => `${key}=${value}`), process.execPath, driver].map(quote).join(" ");
    await invoke(["respawn-pane", "-k", "-t", parent, command]);
    const driverChecks = await until(async () => {
      // Read the pane first: a dead pane still carries the final marker.
      latest = await invoke(["capture-pane", "-p", "-t", parent, "-S", "-200"]);
      const failed = latest.match(/TMUX_SMOKE_FAILED:(.*)$/m);
      if (failed) throw new Error(`driver failure: ${failed[1]}`);
      const passed = latest.match(/TMUX_SMOKE_OK:(\[[^\r\n]*\])$/m);
      if (passed) return JSON.parse(passed[1]);
      if ((await invoke(["display-message", "-p", "-t", parent, "#{pane_dead}"])).trim() === "1") {
        throw new Error(`driver pane exited without a marker: ${latest.slice(-600)}`);
      }
    }, 60000, "driver completion marker", deadline);
    if (!Array.isArray(driverChecks) || !DRIVER_CHECKS.every(check => driverChecks.includes(check))) {
      throw new Error(`incomplete driver checks: ${JSON.stringify(driverChecks)}`);
    }
    // Independent, outside-in assertions: the driver's own checks are not enough
    // to prove the real window and its option chrome exist.
    const windows = (await invoke(["list-windows", "-a", "-F", "#{window_id} #{window_name}"]))
      .trim().split(/\r?\n/).map(line => line.trim()).filter(Boolean)
      .map(line => { const [id, ...name] = line.split(/\s+/); return { id, name: name.join(" ") }; });
    const owned = windows.find(w => w.name === "π subagents" || w.name.startsWith("π subagents · "));
    if (!owned) throw new Error(`no π subagents window: ${windows.map(w => w.name).join(" | ")}`);
    const panes = (await invoke(["list-panes", "-t", owned.id, "-F", "#{pane_id}"])).trim().split(/\s+/).filter(Boolean);
    if (panes.length !== 4) throw new Error(`expected four viewer panes, saw ${panes.length}`);
    const borderStatus = (await invoke(["show-options", "-w", "-t", owned.id, "-v", "pane-border-status"])).trim();
    const borderFormat = await invoke(["show-options", "-w", "-t", owned.id, "-v", "pane-border-format"]);
    const automaticRename = (await invoke(["show-options", "-w", "-t", owned.id, "-v", "automatic-rename"])).trim();
    if (borderStatus !== "top") throw new Error(`pane-border-status=${JSON.stringify(borderStatus)}`);
    if (!/@pi_viewer_summary/.test(borderFormat)) throw new Error(`pane-border-format=${JSON.stringify(borderFormat)}`);
    if (automaticRename !== "off") throw new Error(`automatic-rename=${JSON.stringify(automaticRename)}`);
    for (const pane of panes) {
      const state = (await invoke(["display-message", "-p", "-t", pane, "#{@pi_viewer_state}"])).trim();
      const summary = (await invoke(["display-message", "-p", "-t", pane, "#{@pi_viewer_summary}"])).trim();
      if (state !== "working" && state !== "idle") throw new Error(`viewer state ${JSON.stringify(state)} on ${pane}`);
      if (!summary) throw new Error(`missing viewer summary on ${pane}`);
    }
    const summary = (await invoke(["display-message", "-p", "-t", parent, "#{@pi_subagent_summary}"])).trim();
    if (!/^running 4/.test(summary)) throw new Error(`parent summary=${JSON.stringify(summary)}`);
    checks = [...driverChecks, "window-present", "launcher-viewer-panes", "launcher-window-options", "launcher-viewer-options", "launcher-parent-summary"];
  } catch (error) {
    failure = error;
    failure.message += `\nlast captured pane:\n${latest.slice(-2000)}`;
    try { failure.message += `\nadapter log:\n${(await fs.readFile(path.join(root, "smoke-diagnostics.json"), "utf8")).slice(-8000)}`; } catch { /* absent */ }
  } finally {
    try { if (started) await invoke(["kill-server"]); }
    catch (error) { if (!failure) failure = error; else failure.message += `\nkill-server failed: ${error.message}`; }
    await fs.rm(root, { recursive: true, force: true }).catch(() => {});
  }
  if (failure) throw failure;
  return checks;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  runSmoke().then(checks => console.log(JSON.stringify({ checks })), error => {
    console.error(`TMUX_SMOKE_FAILED: ${error.stack}`);
    process.exitCode = 1;
  });
}
